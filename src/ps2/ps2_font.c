/******************************************************************************

	ps2_font.c

	8x8 bitmap font + CPU framebuffer drawing helpers for the PS2 menu.

	The font is the public-domain font8x8_basic table (ASCII 0x20-0x7E).
	All drawing targets g_menu_fb (declared in ps2_gui.h), a 512x272
	RGBA16 buffer in main RAM. No GS/gsKit calls live here.

******************************************************************************/

