void menu_fb_init(void)
{
	menu_clear(menu_rgb(0, 0, 0));
}

void menu_clear(uint32_t color)
{
	int i;
	for (i = 0; i < MENU_TEX_W * MENU_TEX_H; i++)
		g_menu_fb[i] = color;
}

/* Render a string into an arbitrary RGBA32 buffer (any row pitch) with
 * the 8x8 font. Used by the FPS overlay so it does not have to touch
 * the 512-wide menu framebuffer. */
void font_render_into(uint32_t *buf, int buf_w, int x, int y,
                      const char *s, uint32_t color)
{
	int row, col;

	while (s && *s)
	{
		char c = *s++;
		if (c == '\n') { y += 8; x = 0; continue; }
		if (c < 0x20 || c > 0x7E) c = 0x7F;
		const uint8_t *glyph = (const uint8_t *)&font8x8_basic[(int)(c - 0x20) * 8];
		for (row = 0; row < 8; row++)
		{
			uint8_t bits = glyph[row];
			int py = y + row;
			if (py < 0) continue;
			for (col = 0; col < 8; col++)
			{
				if (bits & (1 << col))
				{
					int px = x + col;
					if (px >= 0 && px < buf_w)
						buf[py * buf_w + px] = color;
				}
			}
		}
		x += 8;
	}
}

void menu_fill_rect(int x, int y, int w, int h, uint32_t color)
{
	int yy, xx;
	for (yy = y; yy < y + h; yy++) {
		if (yy < 0 || yy >= MENU_H) continue;
		for (xx = x; xx < x + w; xx++) {
			if (xx < 0 || xx >= MENU_W) continue;
			g_menu_fb[yy * MENU_TEX_W + xx] = color;
		}
	}
}

void menu_draw_char(int x, int y, char c, uint32_t color)
{
	const uint8_t *glyph;
	int row, col;

	if (c < 0x20 || c > 0x7E)
		c = 0x7F; /* out-of-range -> use '~' cell as fallback box */
	glyph = (const uint8_t *)&font8x8_basic[(int)(c - 0x20) * 8];

	for (row = 0; row < FONT_H; row++) {
		uint8_t bits = glyph[row];
		int py = y + row;
		if (py < 0 || py >= MENU_H) continue;
		for (col = 0; col < FONT_W; col++) {
			/* FIX: font8x8_basic stores bit 0 = LEFTMOST pixel (Daniel Hepper
			 * table). The old 0x80>>col treated bit 7 as leftmost, drawing
			 * every glyph mirrored left-right. */
			if (bits & (1 << col)) {
				int px = x + col;
				if (px >= 0 && px < MENU_W)
					g_menu_fb[py * MENU_TEX_W + px] = color;
			}
		}
	}
}

void menu_draw_text(int x, int y, const char *s, uint32_t color)
{
	int cx = x;
	if (!s) return;
	while (*s) {
		menu_draw_char(cx, y, *s, color);
		cx += FONT_W;
		s++;
	}
}

void menu_draw_text_center(int cx, int y, const char *s, uint32_t color)
{
	int w = menu_text_width(s);
	menu_draw_text(cx - w / 2, y, s, color);
}

int menu_text_width(const char *s)
{
	int n = 0;
	if (!s) return 0;
	while (*s) { n++; s++; }
	return n * FONT_W;
}
